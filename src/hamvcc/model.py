import torch
from torch import nn
import torch.nn.functional as F

class MLPEncoder(nn.Module):
    def __init__(self, d_in, hidden, latent):
        super().__init__()
        self.net = nn.Sequential(nn.Linear(d_in, hidden), nn.GELU(), nn.LayerNorm(hidden), nn.Linear(hidden, latent))
    def forward(self, x):
        return F.normalize(self.net(x), dim=-1)

class HAMVCC(nn.Module):
    def __init__(self, dims, hidden=256, latent=128):
        super().__init__()
        self.encoders = nn.ModuleDict({k: MLPEncoder(v, hidden, latent) for k,v in dims.items()})
        self.reliability_logits = nn.Parameter(torch.zeros(len(dims)))
        self.fuse = nn.Sequential(nn.Linear(latent, latent), nn.GELU(), nn.LayerNorm(latent))
        self.view_names = list(dims.keys())

    def forward(self, xdict, mask, uniform_weights=False):
        z = torch.stack([self.encoders[k](xdict[k]) for k in self.view_names], dim=1)
        logits = self.reliability_logits.unsqueeze(0).expand(z.size(0), -1)
        if uniform_weights:
            logits = torch.zeros_like(logits)
        logits = logits.masked_fill(mask <= 0, -1e9)
        w = torch.softmax(logits, dim=1)
        fused = F.normalize(self.fuse((z * w.unsqueeze(-1)).sum(1)), dim=-1)
        return z, w, fused


def info_nce(z, temperature=0.2):
    n = z.size(0)
    if n < 2:
        return z.sum() * 0.0
    sim = z @ z.T / temperature
    target = torch.arange(n, device=z.device)
    sim.fill_diagonal_(-1e9)
    # positive is generated by pairing each row with a cyclic-shifted row;
    # this gives a stable instance discrimination objective without labels.
    pos = torch.roll(z, shifts=1, dims=0)
    pos_logits = (z * pos).sum(-1) / temperature
    denom = torch.logsumexp(sim, dim=1)
    return -(pos_logits - denom).mean()


def cross_view_loss(z, mask):
    losses=[]
    V=z.size(1)
    for i in range(V):
        for j in range(i+1,V):
            valid=(mask[:,i]*mask[:,j])>0
            if valid.any():
                losses.append(1-(z[valid,i]*z[valid,j]).sum(-1).mean())
    return torch.stack(losses).mean() if losses else z.sum()*0.0


def cluster_consistency(z, mask, k):
    # Soft agreement surrogate: maximize similarity of each view to the fused mean.
    fused = F.normalize((z*mask.unsqueeze(-1)).sum(1) / mask.sum(1,keepdim=True).clamp_min(1), dim=-1)
    view_mean = (z * mask.unsqueeze(-1)).sum(1) / mask.sum(1,keepdim=True).clamp_min(1)
    return (1-(F.normalize(view_mean,dim=-1)*fused).sum(-1)).mean()


def balance_loss(fused, k):
    # Encourage approximately balanced soft assignments using fixed random prototypes.
    # A deterministic prototype bank is generated from the fused dimension.
    d=fused.size(1)
    g=torch.Generator(device=fused.device); g.manual_seed(12345+k)
    p=F.normalize(torch.randn(k,d,generator=g,device=fused.device),dim=-1)
    q=torch.softmax(fused@p.T,dim=1).mean(0)
    target=torch.full_like(q,1.0/k)
    return F.mse_loss(q,target)
